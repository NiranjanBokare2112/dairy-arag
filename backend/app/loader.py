"""Feed rows into the database: schema setup and the data loader.

The loader takes a JSON file {"tables": {table: [row, ...]}} (e.g. scripts/db/sample-data.json, made by
scripts/db/make-sample.mjs) and inserts everything in ONE transaction, in the order the database's guard
triggers allow — the same order real use follows:

  1. masters: center (upsert), users, farmers, rate charts, feed items, advances, sessions, dispatches
  2. bill cycles as 'generated' and bills as 'draft'           (a finalized period refuses new entries)
  3. milk entries, corrections, feed moves, advance recoveries  (attached to the draft bills)
  4. bills → their real status ('final'), cycles → 'finalized'  (now locked by the triggers)
  5. payments (need a final bill; the payments_sync_bill trigger fills bills.paid_paise)
  6. messages, SMS counters, audit log (audit ids come from the identity column)

Values: JSON true/false → boolean, {"$hex": "…"} → bytea, objects/lists → jsonb, strings are cast by
PostgreSQL to date / time / timestamptz / inet. Columns the live table doesn't have are reported and
skipped; required columns the file doesn't carry get a documented default (FILL below).
"""
from __future__ import annotations

import json
from datetime import datetime, timedelta
from pathlib import Path

from sqlalchemy import Connection, text

from .db import TABLES, engine

SCHEMA_FILE = Path(__file__).resolve().parents[1] / "db" / "schema.sql"
MIGRATIONS = Path(__file__).resolve().parents[1] / "db" / "migrations"  # 001_*.sql … applied in name order


def apply_migrations(conn: Connection) -> list[str]:
    """Apply db/migrations/*.sql not yet recorded in schema_migrations (each is additive and safe to re-run)."""
    with conn.connection.dbapi_connection.cursor() as cur:
        cur.execute("CREATE TABLE IF NOT EXISTS public.schema_migrations (name text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now())")
        cur.execute("SELECT name FROM public.schema_migrations")
        done = {r[0] for r in cur.fetchall()}
        applied = []
        for f in sorted(MIGRATIONS.glob("*.sql")):
            if f.name in done:
                continue
            cur.execute(f.read_text(encoding="utf-8"))  # raw cursor: '%' in function bodies stays literal
            cur.execute("INSERT INTO public.schema_migrations (name) VALUES (%s)", (f.name,))
            applied.append(f.name)
    return applied


def _fill_sessions(row: dict) -> None:
    # sessions.expires_at is required in the live schema; sample sessions last 12 hours from login
    if not row.get("expires_at"):
        row["expires_at"] = (datetime.fromisoformat(row["login_at"].replace("Z", "+00:00")) + timedelta(hours=12)).isoformat()


FILL = {"sessions": _fill_sessions}
IDENTITY_SKIP = {"audit_log": {"id"}}  # generated by the database


def apply_schema(conn: Connection) -> None:
    """Create all tables, functions and triggers from backend/db/schema.sql (a pg_dump --schema-only).

    psql meta-commands (\\restrict …) are dropped; the rest runs as plain SQL.
    """
    sql = "\n".join(l for l in SCHEMA_FILE.read_text(encoding="utf-8").splitlines() if not l.startswith("\\"))
    # raw driver cursor with no parameters, so '%' inside function bodies (RAISE '… % …') isn't taken as a placeholder
    with conn.connection.dbapi_connection.cursor() as cur:
        cur.execute(sql)
        cur.execute("SELECT pg_catalog.set_config('search_path', 'public', false)")
    apply_migrations(conn)  # the base dump + every migration = the current schema


def _columns(conn: Connection, table: str) -> dict[str, str]:
    rows = conn.execute(text("select column_name, data_type from information_schema.columns "
                             "where table_schema = 'public' and table_name = :t"), {"t": table})
    return {r[0]: r[1] for r in rows}


def _value(v, data_type: str):
    if isinstance(v, dict) and set(v) == {"$hex"}:
        return bytes.fromhex(v["$hex"])
    if data_type == "boolean" and isinstance(v, int):
        return bool(v)  # 0/1 from other sources
    if data_type in ("jsonb", "json"):
        if v is None:
            return None
        if isinstance(v, str):  # already JSON text
            return v
        return json.dumps(v, ensure_ascii=False)
    return v


def _insert(conn: Connection, table: str, rows: list[dict], report: dict) -> None:
    if not rows:
        return
    cols = _columns(conn, table)
    skip = IDENTITY_SKIP.get(table, set())
    given = [c for c in rows[0] if c in cols and c not in skip]
    extra = sorted(set(rows[0]) - set(cols) - skip)
    if extra:
        report.setdefault("skippedColumns", {})[table] = extra
    fill = FILL.get(table)
    if fill:
        for r in rows:
            fill(r)
        given += [c for c in rows[0] if c in cols and c not in given and c not in skip]
    placeholders = ", ".join(f":{c}" for c in given)
    stmt = text(f'INSERT INTO "{table}" ({", ".join(given)}) VALUES ({placeholders})')
    conn.execute(stmt, [{c: _value(r.get(c), cols[c]) for c in given} for r in rows])
    report["inserted"][table] = report["inserted"].get(table, 0) + len(rows)


def load(data: dict, *, target: str | None = None, reset: bool = False) -> dict:
    """Load a {"tables": {...}} document. Returns a report. All-or-nothing (one transaction)."""
    t = data["tables"]
    report: dict = {"inserted": {}}
    with engine(target).begin() as conn:
        present = {r[0] for r in conn.execute(text("select table_name from information_schema.tables where table_schema='public'"))}
        missing = [x for x in TABLES if x not in present]
        if missing:
            raise SystemExit(f"Tables missing: {', '.join(missing)}. Run:  python -m app.cli migrate   (or init-db on an empty database)")
        if reset:
            # The schema protects the audit log (no UPDATE/DELETE/TRUNCATE), so rows can't be cleared table by table.
            # Reset = REBUILD: keep the center row(s), drop and re-create the schema from db/schema.sql, put the
            # center back, then load. All inside this one transaction — if anything fails, nothing changes.
            keep = [dict(r) for r in conn.execute(text("select * from centers")).mappings()]
            conn.exec_driver_sql("DROP SCHEMA public CASCADE; CREATE SCHEMA public;")
            apply_schema(conn)
            for row in keep:
                cols = _columns(conn, "centers"); keys = [k for k in row if k in cols]
                conn.execute(text(f'INSERT INTO centers ({", ".join(keys)}) VALUES ({", ".join(":" + k for k in keys)})'), {k: _value(row[k], cols[k]) for k in keys})  # jsonb settings back as JSON text
            report["rebuilt"] = True
        else:
            busy = {x: conn.execute(text(f'select count(*) from "{x}"')).scalar() for x in TABLES if x != "centers"}
            busy = {k: v for k, v in busy.items() if v}
            if busy:
                raise SystemExit(f"The database already has data ({busy}). Use --reset to replace it (this deletes everything).")

        # 1. center: insert only if missing — an existing center row (real settings the owner entered) is kept as is
        for row in t.get("centers", []):
            cols = _columns(conn, "centers")
            keys = [k for k in row if k in cols]
            added = conn.execute(text(f'INSERT INTO centers ({", ".join(keys)}) VALUES ({", ".join(":" + k for k in keys)}) '
                                      f'ON CONFLICT (id) DO NOTHING'), {k: _value(row[k], cols[k]) for k in keys}).rowcount
            if added:
                report["inserted"]["centers"] = report["inserted"].get("centers", 0) + 1
            else:
                report.setdefault("kept", []).append(f"centers/{row['id']} (existing row not changed)")
        for name in ("users", "farmers", "rate_charts", "rate_chart_cells", "feed_items", "advances", "sessions", "dispatches", "milk_buyers"):
            _insert(conn, name, t.get(name, []), report)

        # 2. cycles as generated, bills as draft (real statuses applied in step 4)
        cycles = t.get("bill_cycles", [])
        _insert(conn, "bill_cycles", [{**c, "status": "generated" if c["status"] == "finalized" else c["status"]} for c in cycles], report)
        bills = t.get("bills", [])
        _insert(conn, "bills", [{**b, "status": "draft", "paid_paise": 0} for b in bills], report)

        # 3. entries and everything that points at the draft bills
        for name in ("collections", "corrections", "feed_moves", "advance_recoveries", "buyer_sales", "buyer_payments", "counter_sales"):
            _insert(conn, name, t.get(name, []), report)

        # 4. finalize: bills, then cycles (from now on the triggers lock them)
        for b in bills:
            if b["status"] != "draft":
                conn.execute(text("UPDATE bills SET status = :s WHERE id = :id"), {"s": b["status"], "id": b["id"]})
        for c in cycles:
            if c["status"] == "finalized":
                conn.execute(text("UPDATE bill_cycles SET status = 'finalized', finalized_at = :at, finalized_by = :by WHERE id = :id"),
                             {"at": c["finalized_at"], "by": c["finalized_by"], "id": c["id"]})

        # 5. payouts (D-107), then payments — the trigger recomputes bills.paid_paise; check it matches the file
        _insert(conn, "payout_runs", t.get("payout_runs", []), report)
        _insert(conn, "payouts", t.get("payouts", []), report)
        _insert(conn, "payments", t.get("payments", []), report)
        want = {b["id"]: b["paid_paise"] for b in bills}
        got = dict(conn.execute(text("select id, paid_paise from bills")).all())
        diff = {k: (want[k], got.get(k)) for k in want if want[k] != got.get(k)}
        if diff:
            raise SystemExit(f"paid_paise after payments differs from the file: {diff}")

        # 6. the rest
        for name in ("expense_categories", "expenses", "change_requests", "schemes", "doctors", "broadcasts", "tickets", "ticket_messages", "ticket_notifications", "outbox_messages", "sms_counters", "audit_log", "buyer_months"):  # notices before their messages; closed buyer months last: they lock their sales
            _insert(conn, name, t.get(name, []), report)
    return report


def load_file(path: str | Path, **kw) -> dict:
    return load(json.loads(Path(path).read_text(encoding="utf-8")), **kw)
